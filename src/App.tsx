import { lazy, Suspense, useMemo } from 'react'
import { ScrollReveal } from './animations/ScrollReveal'
import { useLenis } from './animations/useLenis'
import { BeforeAfterSlider } from './effects/BeforeAfterSlider'
import { HorizontalScroll } from './effects/HorizontalScroll'
import { Parallax } from './effects/Parallax'
import { TextReveal } from './effects/TextReveal'
import { ScrollSequence } from './video/ScrollSequence'

const RotatingObject = lazy(() =>
  import('./3d/RotatingObject').then((m) => ({ default: m.RotatingObject })),
)

const DEMO_FRAME_COUNT = 20
const demoFrameUrls = Array.from(
  { length: DEMO_FRAME_COUNT },
  (_, i) => `/demo-sequence/frame-${String(i + 1).padStart(4, '0')}.webp`,
)

function Panel({ label, className }: { label: string; className?: string }) {
  return (
    <div
      className={`flex h-[80vh] w-[80vw] shrink-0 items-center justify-center rounded-2xl border border-neutral-800 text-2xl font-semibold ${className ?? ''}`}
    >
      {label}
    </div>
  )
}

function App() {
  useLenis()
  const frameUrls = useMemo(() => demoFrameUrls, [])

  return (
    <main className="bg-neutral-950 text-neutral-100">
      <section className="flex min-h-screen flex-col items-center justify-center gap-4 px-6 text-center">
        <h1 className="text-3xl font-semibold tracking-tight">Yonah Creative Engine</h1>
        <p className="max-w-md text-sm text-neutral-400">
          Foundation through Phase 6 running live. Scroll for GSAP ScrollTrigger, React Three
          Fiber, a WebP scroll sequence, horizontal scroll, parallax, and a before/after slider.
        </p>
      </section>

      <section className="flex min-h-screen items-center justify-center">
        <Suspense fallback={null}>
          <RotatingObject className="h-[60vh] w-full max-w-xl" />
        </Suspense>
      </section>

      <ScrollReveal className="flex min-h-screen flex-col items-center justify-center gap-4 px-6 text-center">
        <h2 className="text-2xl font-semibold tracking-tight">Scroll-triggered reveal</h2>
        <p className="max-w-md text-sm text-neutral-400">
          This section fades and slides in via GSAP ScrollTrigger, driven by Lenis smooth scroll.
        </p>
      </ScrollReveal>

      <div className="flex min-h-screen flex-col items-center justify-center gap-4 px-6 text-center">
        <h2 className="text-2xl font-semibold tracking-tight">Scroll-controlled video sequence</h2>
        <p className="max-w-md text-sm text-neutral-400">
          A tiny synthetic 20-frame WebP sequence, generated by this repo's own FFmpeg pipeline —
          scrub by scrolling.
        </p>
      </div>
      <ScrollSequence frameUrls={frameUrls} />

      <section className="flex min-h-screen flex-col items-center justify-center gap-10 px-6">
        <Parallax distance={-120}>
          <h2 className="text-4xl font-semibold tracking-tight">Parallax layer</h2>
        </Parallax>
        <Parallax distance={60} className="opacity-60">
          <p className="max-w-md text-center text-sm text-neutral-400">
            This paragraph drifts at a different rate than the heading above it as you scroll.
          </p>
        </Parallax>
      </section>

      <HorizontalScroll className="h-screen">
        <Panel label="Panel 1" className="mr-8 bg-neutral-900" />
        <Panel label="Panel 2" className="mr-8 bg-neutral-900" />
        <Panel label="Panel 3" className="bg-neutral-900" />
      </HorizontalScroll>

      <section className="flex min-h-screen flex-col items-center justify-center gap-6 px-6 text-center">
        <TextReveal
          text="Each word in this sentence reveals on its own as you scroll into view."
          className="max-w-2xl text-3xl font-semibold tracking-tight"
        />
      </section>

      <section className="flex min-h-screen flex-col items-center justify-center gap-6 px-6">
        <h2 className="text-2xl font-semibold tracking-tight">Before / after slider</h2>
        <BeforeAfterSlider
          beforeSrc="/demo-sequence/frame-0001.webp"
          afterSrc="/demo-sequence/frame-0020.webp"
          className="h-[50vh] w-full max-w-xl rounded-2xl"
        />
      </section>
    </main>
  )
}

export default App
