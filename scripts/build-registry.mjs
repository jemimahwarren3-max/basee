// Builds src/components/registry.ts from the .astro files and checks that every
// section id named by a design family resolves to a real component.
// Usage: npm run registry
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src');
const componentsDir = join(srcDir, 'components');
const familiesDir = join(srcDir, 'design-families');
const outFile = join(componentsDir, 'registry.ts');

const kebab = (s) =>
  s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase();

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

function topLevelPropNames(src) {
  const start = src.indexOf('interface Props');
  if (start === -1) return [];
  let depth = 0;
  let body = '';
  for (let i = src.indexOf('{', start); i < src.length; i++) {
    const c = src[i];
    if (c === '{') depth++;
    if (c === '}') depth--;
    if (depth === 0) break;
    if (depth === 1) body += c;
  }
  return [...body.matchAll(/(\w+)\??\s*:/g)].map((m) => m[1]);
}

const components = [];
for (const file of walk(componentsDir).filter((f) => f.endsWith('.astro'))) {
  const src = readFileSync(file, 'utf8');
  const name = basename(file, '.astro');
  const category = relative(componentsDir, dirname(file)).split(/[\\/]/)[0] || 'common';
  components.push({
    id: kebab(name),
    name,
    category,
    path: relative(srcDir, file).replace(/\\/g, '/'),
    props: topLevelPropNames(src),
    hasAnimation: /<script|@keyframes|animation|transition/.test(src),
  });
}

const errors = [];
const seen = new Map();
for (const c of components) {
  if (seen.has(c.id)) errors.push(`duplicate id "${c.id}": ${seen.get(c.id)} and ${c.path}`);
  seen.set(c.id, c.path);
}

const familyRefs = [];
for (const file of readdirSync(familiesDir).filter((f) => f.endsWith('.ts') && f !== 'types.ts' && f !== 'index.ts')) {
  const src = readFileSync(join(familiesDir, file), 'utf8');
  for (const m of src.matchAll(/(preferredHero|preferredSections|avoidSections):\s*\[([^\]]*)\]/g)) {
    for (const id of m[2].matchAll(/'([^']+)'/g)) {
      familyRefs.push({ family: file.replace('.ts', ''), list: m[1], id: id[1] });
    }
  }
}
for (const ref of familyRefs) {
  if (!seen.has(ref.id)) errors.push(`${ref.family}.${ref.list} references unknown component "${ref.id}"`);
}

const body = components
  .sort((a, b) => a.id.localeCompare(b.id))
  .map(
    (c) =>
      `  {\n    id: '${c.id}',\n    name: '${c.name}',\n    category: '${c.category}',\n    path: '${c.path}',\n    props: [${c.props.map((p) => `'${p}'`).join(', ')}],\n    hasAnimation: ${c.hasAnimation},\n  },`,
  )
  .join('\n');

writeFileSync(
  outFile,
  `// Generated by scripts/build-registry.mjs. Run \`npm run registry\` after adding or renaming components.\nimport type { ComponentMeta } from '../design-families/types';\n\nexport const COMPONENTS: ComponentMeta[] = [\n${body}\n];\n`,
);

console.log(`Registered ${components.length} components, checked ${familyRefs.length} family references.`);
if (errors.length) {
  console.error(`\n${errors.length} problem(s):`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}
